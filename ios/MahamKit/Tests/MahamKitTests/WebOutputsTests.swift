import Foundation
import Testing

@testable import MahamKit

// What the web's own functions return (src/lib/format.ts, money.ts, dates.ts
// and words.ts, run in Node 22 with ICU 78 / CLDR 48, the device's zone set
// to Asia/Kuwait), for inputs past the web's test cases: negative and
// half-way amounts, the Arabic marks, foreign currencies, invalid input.

@Suite("The web's outputs")
struct WebOutputTests {
  let kuwait = TimeZone(identifier: "Asia/Kuwait") ?? .current

  @Test("money, unit prices and plain amounts")
  func money() {
    for (amount, currency, locale, display, expected) in WebOutputs.money {
      let text = Format.money(amount, currency: currency, locale: FormatLocale(locale), display: display)
      #expect(text == expected, "\(amount) \(currency) \(locale) \(display)")
      // A Decimal reads the same as the Double it came from.
      let exact = Format.money(Money.dec(amount), currency: currency, locale: FormatLocale(locale), display: display)
      #expect(exact == expected, "\(amount) \(currency) \(locale) \(display) as Decimal")
    }
    for (amount, currency, locale, display, expected) in WebOutputs.unitPrice {
      let text = Format.unitPrice(amount, currency: currency, locale: FormatLocale(locale), display: display)
      #expect(text == expected, "\(amount) \(currency) \(locale)")
    }
    for (amount, currency, locale, expected) in WebOutputs.amount {
      #expect(Format.amount(amount, currency: currency, locale: FormatLocale(locale)) == expected, "\(amount) \(currency) \(locale)")
    }
  }

  @Test("quantities, percentages and currency symbols")
  func numbers() {
    for (quantity, locale, expected) in WebOutputs.quantity {
      #expect(Format.quantity(quantity, locale: FormatLocale(locale)) == expected, "\(quantity) \(locale)")
    }
    for (rate, locale, expected) in WebOutputs.percent {
      #expect(Format.percent(rate, locale: FormatLocale(locale)) == expected, "\(rate) \(locale)")
    }
    for (currency, locale, display, expected) in WebOutputs.symbol {
      #expect(Format.currencySymbol(currency, locale: FormatLocale(locale), display: display) == expected, "\(currency) \(locale)")
    }
  }

  @Test("dates and moments")
  func dates() {
    for (value, format, locale, expected) in WebOutputs.date {
      #expect(Format.date(value, format: Format.DateFormat(format), locale: FormatLocale(locale)) == expected, "\(value ?? "nil") \(format) \(locale)")
    }
    for (value, locale, format, expected) in WebOutputs.dateTime {
      let text = Format.dateTime(value, locale: FormatLocale(locale), dateFormat: format.map { Format.DateFormat($0) }, zone: kuwait)
      #expect(text == expected, "\(value) \(locale) \(format ?? "nil")")
    }
  }

  @Test("amounts on screen and masked numbers")
  func screens() {
    for (text, expected) in WebOutputs.isolate {
      #expect(Format.isolateAmount(text, locale: .arabicKuwait) == expected, "\(text)")
    }
    for (value, visible, expected) in WebOutputs.mask {
      #expect(Format.maskNumber(value, visible: visible) == expected, "\(value) \(visible)")
    }
  }

  @Test("decimals, rounding and minor units")
  func decimals() {
    for (text, expected) in WebOutputs.decText {
      #expect(Money.dec(text) == Money.dec(expected), "\(text)")
    }
    for (number, expected) in WebOutputs.decNumber {
      #expect(Money.dec(number) == Money.dec(expected), "\(number)")
    }
    for (value, places, expected) in WebOutputs.round {
      #expect(Money.round(value, places) == Money.dec(expected), "\(value) \(places)")
    }
    for (input, expected) in WebOutputs.parseAmount {
      let parsed = Money.parseAmount(input)
      #expect(parsed == expected && parsed.sign == expected.sign, "\(input)")
    }
    for (value, places, expected) in WebOutputs.toMinor {
      #expect(Money.toMinor(value, places) == expected, "\(value) \(places)")
    }
    for (minor, places, expected) in WebOutputs.fromMinor {
      #expect(Money.fromMinor(minor, places) == Money.dec(expected), "\(minor) \(places)")
    }
    for (currency, expected) in WebOutputs.precision {
      #expect(Money.precision(currency) == expected, "\(currency)")
    }
    for (a, b, currency, expected) in WebOutputs.sameAmount {
      #expect(Money.sameAmount(a, b, currency: currency) == expected, "\(a) \(b) \(currency)")
    }
    for (number, expected) in WebOutputs.jsString {
      #expect(Money.jsString(number) == expected)
    }
  }

  @Test("calendar days")
  func days() {
    for (value, expected) in WebOutputs.isISODate {
      #expect(ISODates.isISODate(value) == expected, "\(value)")
    }
    for (value, days, expected) in WebOutputs.addDays {
      #expect(ISODates.addDays(value, days) == expected, "\(value) \(days)")
    }
    for (from, to, expected) in WebOutputs.daysBetween {
      #expect(ISODates.daysBetween(from, to) == expected, "\(from) \(to)")
    }
    for (start, frequency, index, expected) in WebOutputs.occurrence {
      #expect(ISODates.occurrenceDate(start, frequency, index) == expected, "\(start) \(frequency) \(index)")
    }
  }

  @Test("amounts in words")
  func words() {
    for (number, expected) in WebOutputs.englishNumber {
      #expect(Words.englishNumber(number) == expected, "\(number)")
    }
    for (number, gender, expected) in WebOutputs.arabicNumber {
      #expect(Words.arabicNumber(number, gender: gender) == expected, "\(number) \(gender)")
    }
    for (amount, currency, language, expected) in WebOutputs.words {
      #expect(Words.amountInWords(amount, currency: currency, language: language) == expected, "\(amount) \(currency) \(language)")
    }
  }
}

